"""Phase-2 tables (no API calls) -> results/TABLES_P2.md"""
import glob
import json
import os
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
from analyze import boot_ci  # noqa: E402
from analyze_p2 import load_all, p1_usd  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
OUT = []


def p(s=""):
    OUT.append(s)


def table(D, names, refs, title):
    names = [n for n in names if n in D]
    q = sorted(set.intersection(*[set(D[n]) for n in names + [r for r in refs if r in D]]))
    p(f"\n### {title} (n={len(q)})\n")
    p("| condition | score [95% CI] | $/1k q | rounds loaded | full-set recall | " + " | ".join(f"Δ vs {r}" for r in refs) + " |")
    p("|---|---|---:|---:|---:|" + "---|" * len(refs))
    for n in names:
        s = np.array([D[n][x]["score"] for x in q])
        lo, hi = boot_ci(s)
        usd = 1000 * np.mean([D[n][x].get("usd", 0) for x in q])
        nl = [D[n][x].get("n_loaded") for x in q if D[n][x].get("n_loaded")]
        fl = [D[n][x]["full"] for x in q if D[n][x].get("n_gold") and D[n][x].get("full") is not None]
        cells = []
        for r in refs:
            if r in D and r != n:
                d = s - np.array([D[r][x]["score"] for x in q])
                l2, h2 = boot_ci(d)
                cells.append(f"{d.mean():+.3f} [{l2:+.3f}, {h2:+.3f}]")
            else:
                cells.append("—")
        p(f"| {n} | {s.mean():.3f} [{lo:.3f}, {hi:.3f}] | {usd:.2f} | {np.mean(nl) if nl else float('nan'):.1f} | "
          f"{np.mean(fl) if fl else float('nan'):.3f} | " + " | ".join(cells) + " |")


def load_dir(d, reader, p1=None):
    """phase-2 files in d for reader; optional phase-1 files (dict name->path) added with computed usd"""
    D = {}
    for f in glob.glob(str(ROOT / d / f"*__{reader}*.jsonl")):
        stem = os.path.basename(f)[:-6]
        if not stem.endswith(reader):
            continue
        stem = stem.replace(f"__{reader}", "")
        sel, rd = stem.split("__")[:2]
        name = sel.replace("-", ":") + "|" + rd.replace("-", ":", 1)
        D[name] = {json.loads(l)["qid"]: json.loads(l) for l in open(f)}
    for name, path in (p1 or {}).items():
        if os.path.exists(ROOT / path):
            R = {}
            for l in open(ROOT / path):
                r = json.loads(l)
                r["usd"] = p1_usd(r, reader)
                r["n_loaded"] = len(r.get("retrieved", [])) or None
                R[r["qid"]] = r
            D[name] = R
    return D


