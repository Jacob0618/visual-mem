"""Regenerate every table used in REPORT.md from results/ (no API calls). Output: results/TABLES.md"""
import json
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
from analyze import boot_ci, load, usd_per_1k  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
OUT = []


def p(s=""):
    OUT.append(s)


def paired(D, a, b, qids=None, field="score"):
    q = sorted(set(D[a]) & set(D[b]) & (set(qids) if qids else set(D[a])))
    d = np.array([D[a][x][field] - D[b][x][field] for x in q], float)
    lo, hi = boot_ci(d)
    return f"{d.mean():+.3f} [{lo:+.3f}, {hi:+.3f}]", len(q)


def cond_table(D, names, title, qids=None, field="score"):
    p(f"\n### {title}\n")
    p("| condition | n | mean [95% CI] | prompt tok/q | cached | read $/1k q |")
    p("|---|---:|---|---:|---:|---:|")
    for n in names:
        if n not in D:
            continue
        R = [r for q, r in D[n].items() if qids is None or q in qids]
        s = np.array([r[field] for r in R], float)
        lo, hi = boot_ci(s)
        pt = np.mean([r["usage"]["prompt"] for r in R])
        cf = np.sum([r["usage"]["cached"] for r in R]) / max(1, np.sum([r["usage"]["prompt"] for r in R]))
        p(f"| {n} | {len(R)} | {s.mean():.3f} [{lo:.3f}, {hi:.3f}] | {pt:,.0f} | {cf:.0%} | {usd_per_1k(R):.2f} |")


def main():
    mm_sets = {"MemEye-dev (method selection)": "results/mm/memeye_dev",
               "MemEye-test (held-out)": "results/mm/memeye_test",
               "Mem-Gallery subset (held-out)": "results/mm/memgal_heldout"}
    main_conds = ["fc__raw-low", "fc__raw-medium", "fc__raw-high", "fc__cap-dense", "fc__cap-short", "fc__none",
                  "cap-dense-10__raw-low", "cap-dense-20__raw-low", "cap-dense-40__raw-low", "cap-dense-10__raw-high",
                  "cap-dense-10__cap-dense", "inter-10__raw-high", "inter-40__raw-low", "sess+cap-dense-10__raw-low",
                  "nbr2+cap-dense-10__raw-low", "fc+cap-dense-10__mix-low-high", "oracle__raw-low", "oracle__raw-high",
                  "oracle__cap-dense", "oracle__cap-short", "oracle__none"]
    p("# Tables (generated by scripts/make_tables.py)")
    p("\n## A. Multimodal memory: all conditions")
    for title, d in mm_sets.items():
        D = load(ROOT / d)
        cond_table(D, main_conds, title)
    D = load(ROOT / "results/mm/memgal_heldout_half")
    cond_table(D, main_conds, "Mem-Gallery half subset (secondary conditions)")

    p("\n## B. Pre-registered contrasts (paired Δ, 95% bootstrap CI)\n")
    contrasts = [("H1a FC-low − RAG@10", "fc__raw-low", "cap-dense-10__raw-low"),
                 ("H1b FC-low − RAG@40", "fc__raw-low", "cap-dense-40__raw-low"),
                 ("H2 FC-low − FC-high", "fc__raw-low", "fc__raw-high"),
                 ("H3 FC-low − FC-dense-caption", "fc__raw-low", "fc__cap-dense"),
                 ("H4a oracle short − dense caption", "oracle__cap-short", "oracle__cap-dense"),
                 ("H4b oracle dense caption − raw-low", "oracle__cap-dense", "oracle__raw-low"),
                 ("H5e RAG@10 caption-key − interleaved-key (raw:high)", "cap-dense-10__raw-high", "inter-10__raw-high"),
                 ("H6 zoom − FC-low", "fc+cap-dense-10__mix-low-high", "fc__raw-low")]
    p("| contrast | MemEye-dev | MemEye-test | Mem-Gallery |")
    p("|---|---|---|---|")
    Ds = [load(ROOT / d) for d in mm_sets.values()]
    Dh = load(ROOT / "results/mm/memgal_heldout_half")
    for lab, a, b in contrasts:
        cells = []
        for i, D in enumerate(Ds):
            DD = Dh if (i == 2 and (a not in D or b not in D)) else D
            if a in DD and b in DD:
                s, n = paired(DD, a, b)
                cells.append(f"{s} (n={n})")
            else:
                cells.append("—")
        p(f"| {lab} | " + " | ".join(cells) + " |")

    p("\n## C. Retrieval keys: gold-clue coverage@10 (retrieval only)\n")
    p("| key | MemEye-dev | MemEye-test | Mem-Gallery |")
    p("|---|---:|---:|---:|")
    R = {b: json.load(open(ROOT / f"results/mm/retrieval_{b}.json")) for b in ["memeye_dev", "memeye_test", "memgal_all"]}
    for k in ["img", "text", "inter", "cap:dense", "cap:short"]:
        p(f"| {k} | " + " | ".join(f"{R[b][k + '||ALL']['cov@10']:.3f}" for b in R) + " |")
    p("\nPaired Δ coverage@10 [95% CI]:\n")
    rng = np.random.default_rng(0)
    p("| contrast | MemEye-dev | MemEye-test | Mem-Gallery |")
    p("|---|---|---|---|")
    for a, c in [("cap:short", "inter"), ("cap:dense", "inter"), ("cap:short", "cap:dense"), ("inter", "img"),
                 ("inter", "text")]:
        cells = []
        for b in R:
            P = json.load(open(ROOT / f"results/mm/retrieval_{b}_perq_cov10.json"))
            q = sorted(P[a])
            d = np.array([P[a][x] - P[c][x] for x in q])
            bs = rng.choice(d, size=(10000, len(d))).mean(1)
            cells.append(f"{d.mean():+.3f} [{np.percentile(bs, 2.5):+.3f}, {np.percentile(bs, 97.5):+.3f}]")
        p(f"| {a} − {c} | " + " | ".join(cells) + " |")
    p("\nModality gap (raw cosine under the image-only key): mean score of gold image rounds vs. non-gold text-only rounds\n")
    p("| set | gold image rounds | non-gold text rounds |")
    p("|---|---:|---:|")
    for b in R:
        g = R[b]["_gap"]
        p(f"| {b} | {g['img||gold_img'][0]} | {g['img||nongold_txt'][0]} |")

    p("\n## D. Where does retrieval lose? (MemEye dev+test pooled, FC-low minus RAG, by # gold clue rounds)\n")
    rows = []
    for split in ["dev", "test"]:
        d = ROOT / f"results/mm/memeye_{split}"
        fc = {json.loads(l)["qid"]: json.loads(l) for l in open(d / "fc__raw-low.jsonl")}
        for k in [10, 40]:
            rg = {json.loads(l)["qid"]: json.loads(l) for l in open(d / f"cap-dense-{k}__raw-low.jsonl")}
            for q in fc:
                rows.append((k, rg[q].get("n_gold", 0), rg[q].get("full"), fc[q]["score"] - rg[q]["score"]))
    p("| k | 1 clue round | 2-3 | >=4 | all clues retrieved | some clue missed |")
    p("|---:|---|---|---|---|---|")
    for k in [10, 40]:
        def m(f):
            v = [g for kk, n, full, g in rows if kk == k and f(n, full)]
            return f"{np.mean(v):+.3f} (n={len(v)})"
        p(f"| {k} | {m(lambda n, f: n == 1)} | {m(lambda n, f: 2 <= n <= 3)} | {m(lambda n, f: n >= 4)} | "
          f"{m(lambda n, f: f == 1.0)} | {m(lambda n, f: f == 0.0)} |")

    p("\n## E. Scale stress test (MemEye-dev 100-q subset; + distractor images from Mem-Gallery)\n")
    keep = set(json.load(open(ROOT / "results/memeye_dev_scale100.json"))["qids"])
    D0 = load(ROOT / "results/mm/memeye_dev")
    levels = {0: D0, 250: load(ROOT / "results/mm/scale_dx250"), 1000: load(ROOT / "results/mm/scale_dx1000")}
    p("| + distractor images | FC-low | RAG@10 | RAG@40 | FC prompt tok/q | FC read $/1k q |")
    p("|---:|---|---|---|---:|---:|")
    for lv, D in levels.items():
        cells = []
        for c in ["fc__raw-low", "cap-dense-10__raw-low", "cap-dense-40__raw-low"]:
            if c in D:
                s = np.array([r["score"] for q, r in D[c].items() if q in keep])
                lo, hi = boot_ci(s)
                cells.append(f"{s.mean():.3f} [{lo:.3f}, {hi:.3f}]")
            else:
                cells.append("—")
        fcR = [r for q, r in D.get("fc__raw-low", {}).items() if q in keep]
        tok = f"{np.mean([r['usage']['prompt'] for r in fcR]):,.0f}" if fcR else "—"
        usd = f"{usd_per_1k(fcR):.1f}" if fcR else "—"
        p(f"| {lv} | " + " | ".join(cells) + f" | {tok} | {usd} |")
    for lv in [250, 1000]:
        D = levels[lv]
        for c in ["fc__raw-low", "cap-dense-40__raw-low"]:
            if c in D and c in D0:
                q = sorted(keep & set(D[c]) & set(D0[c]))
                d = np.array([D[c][x]["score"] - D0[c][x]["score"] for x in q])
                lo, hi = boot_ci(d)
                p(f"- Δ({c}, +{lv} vs +0) = {d.mean():+.3f} [{lo:+.3f}, {hi:+.3f}] (n={len(q)})")

    p("\n## G. Reader strength (MemEye; same retrieval/prompts; reader gemini-3.1-flash-lite vs gemini-3.8-flash)\n")
    p("| set | reader | FC-low | RAG@10 | RAG@40 | oracle-low | FC − RAG@10 | FC − oracle |")
    p("|---|---|---|---|---|---|---|---|")
    for split in ["dev", "test"]:
        D = load(ROOT / f"results/mm/memeye_{split}")
        for rd, sfx in [("3.8-flash", ""), ("3.1-flash-lite", "__gemini-3.1-flash-lite")]:
            names = [f"fc__raw-low{sfx}", f"cap-dense-10__raw-low{sfx}", f"cap-dense-40__raw-low{sfx}", f"oracle__raw-low{sfx}"]
            if not all(n in D for n in names):
                continue
            means = [np.mean([r["score"] for r in D[n].values()]) for n in names]
            d1, _ = paired(D, names[0], names[1])
            d2, _ = paired(D, names[0], names[3])
            p(f"| MemEye-{split} | {rd} | " + " | ".join(f"{m:.3f}" for m in means) + f" | {d1} | {d2} |")

    p("\n## F. Text memory verification\n")
    for title, d in [("LoCoMo (1,540 q)", "results/text/locomo"), ("LongMemEval-S stratified (119 q)", "results/text/lme_S")]:
        D = load(ROOT / d)
        names = ["full", "cos-100", "cos-50", "cos-25", "cos-10", "oracle", "oracle_sess"]
        cond_table(D, names, title + " — strict LongMemEval judge")
        if "full" in D and "score_mem0" in next(iter(D["full"].values())):
            cond_table(D, names, title + " — lenient Mem0 judge", field="score_mem0")
        for n in names[1:]:
            if n in D:
                s, k = paired(D, n, "full")
                p(f"- {n} − full: {s} (n={k})")
    (ROOT / "results/TABLES.md").write_text("\n".join(OUT) + "\n")
    print("\n".join(OUT))


if __name__ == "__main__":
    main()
